"""Copy the vLLM/SGLang benchmark's text outputs into the PR branch (overnight_artifacts/bench1021/),
then commit and push to dghosef/mstar perf/overnight-all. Text only: reports, per-model summaries and
raw results.jsonl, gate/decision/failure logs, and the harnesses. No media, traces or server logs.

  python3 publish_artifacts.py            # copy + commit + push
  python3 publish_artifacts.py --dry-run  # copy only, show the diff stat
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

HOME = Path.home()
SRC = HOME / "runs/bench1021"
TREE = HOME / "mstar-ovn-all"
DST = TREE / "overnight_artifacts/bench1021"
KEEP = {"results.jsonl", "summary.md", "summary_main.md", "notes.txt", "decisions.jsonl", "failures.jsonl",
        "gate.txt", "gate_summary.txt", "gate.md", "tuned.json", "tune.json", "versions.jsonl", "startup.jsonl",
        "caveats.txt", "hardware.txt", "REPORT_DIFFUSION.md", "REPORT_TTS.md", "knob_failed.json", "health.json"}
SKIP_DIRS = {"cells", "servers", "gallery", "stages", "profile", "data", "smoke", "evidence", "parity_video"}


def copy_results():
    out = DST / "results"
    if out.exists():
        shutil.rmtree(out)
    n = 0
    for p in (SRC / "results").rglob("*"):
        rel = p.relative_to(SRC / "results")
        if not p.is_file() or set(rel.parts[:-1]) & SKIP_DIRS:
            continue
        if p.name in KEEP or (p.name.startswith("gsm8k_") and p.suffix == ".json") or \
                (p.name.startswith("wer_") and p.suffix == ".json") or (p.parent.name == "gate" and p.suffix == ".md"):
            (out / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, out / rel)
            n += 1
    return n


def copy_harness():
    for name in ("harness", "diffusion_harness"):
        dst = DST / name
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(SRC / name, dst, ignore=shutil.ignore_patterns("*.bak*", "__pycache__", "bak_*", "*.log"))
    for f in ("REPORT.md", "BRIEF.md"):
        if (SRC / f).exists():
            shutil.copy2(SRC / f, DST / f)
    shutil.copy2(HOME / "runs/overnight/BENCH_HEAD.md", DST / "HEADLINES.md")


def main():
    DST.mkdir(parents=True, exist_ok=True)
    n = copy_results()
    copy_harness()
    (DST / "README.md").write_text(
        "# vLLM / SGLang / diffusers benchmark of this branch (Oct 21-23, 2026)\n\n"
        "Text outputs of the head-to-head benchmark summarised in the PR description (HEADLINES.md is that\n"
        "section). Code under test: mstar-pr = d248477ec (this branch's code; the commits after it only add\n"
        "artifacts), mstar-main = abdfd5802.\n\n"
        "- `REPORT.md`: text lane report (generated by `harness/report.py`).\n"
        "- `results/<model>/`: per-model `summary.md` / `summary_main.md`, raw `results.jsonl` (one row per\n"
        "  timed cell), gate results, tuning choices, engine versions. `results/diffusion/` is node2's lane\n"
        "  (diffusion, TTS and others).\n"
        "- `results/decisions.jsonl`, `results/failures.jsonl`: every rule-based decision and every recorded failure.\n"
        "- `harness/` (node8: text, vision, Omni) and `diffusion_harness/` (node2): the unattended runners.\n\n"
        "No media, traces or server logs (too large).\n")
    print(f"copied {n} result files")
    subprocess.run(["git", "-C", str(TREE), "add", "-f", str(DST)], check=True)
    stat = subprocess.run(["git", "-C", str(TREE), "diff", "--cached", "--stat"], capture_output=True, text=True).stdout
    print(stat.splitlines()[-1] if stat.strip() else "no changes")
    if "--dry-run" in sys.argv or not stat.strip():
        return
    # refuse to publish anything that looks like a credential
    scan = subprocess.run(["git", "-C", str(TREE), "diff", "--cached", "-U0"], capture_output=True, text=True).stdout
    token_shapes = [r"hf_[A-Za-z0-9]{30,}", r"ghp_[A-Za-z0-9]{30,}", r"sk-[A-Za-z0-9_-]{30,}",
                    r"AKIA[0-9A-Z]{16}", r"-----BEGIN [A-Z ]*PRIVATE KEY-----"]
    for pat in token_shapes:
        hits = [ln for ln in scan.splitlines() if ln.startswith("+") and re.search(pat, ln)]
        if hits:
            sys.exit(f"refusing to commit: possible secret ({pat}): {hits[0][:120]}")
    subprocess.run(["git", "-C", str(TREE), "commit", "-q", "-m",
                    "overnight_artifacts: vLLM/SGLang benchmark results so far\n\n"
                    "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"], check=True)
    subprocess.run(["git", "-C", str(TREE), "push", "-q", "dghosef", "HEAD:perf/overnight-all"], check=True)
    print("pushed", subprocess.run(["git", "-C", str(TREE), "rev-parse", "--short", "HEAD"],
                                   capture_output=True, text=True).stdout.strip())


if __name__ == "__main__":
    main()
